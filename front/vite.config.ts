import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";

// Vite 是前端的开发服务器兼打包器。开发时它跑在 5173 端口，把 .tsx 即时编译成
// 浏览器能执行的代码；改一行代码，浏览器里对应的组件会热替换，不用刷新整页。
export default defineConfig({
  plugins: [react()],
  server: {
    // 显式绑到 IPv4 回环。Vite 的默认值只监听 [::1]，于是 http://127.0.0.1:5173
    // 连不上——浏览器里输 localhost 能用（它会同时试 IPv6 和 IPv4），但 curl
    // 这类工具不会回退，排查时容易被这一点绊住。
    //
    // 不用 host: true：那会绑到所有网卡，把开发服务器暴露给同网段的人，
    // 而它背后的后端可以在本机执行任意命令。
    host: "127.0.0.1",
    port: 5173,
    // proxy 把前端发往 /api 的请求转发到后端的 8765 端口。
    //
    // 为什么需要它：浏览器的同源策略规定，5173 上的页面不能直接请求 8765——
    // 那是"跨源"。解决办法有两个，一是后端开 CORS 明确允许，二是让开发服务器
    // 代理转发，使浏览器眼里所有请求都发往 5173，压根不跨源。
    //
    // 这里选代理：CORS 是给跨源生产部署用的，本机开发引入它只是多一处配置和
    // 一类难查的错误（预检请求失败、响应头漏了某个字段之类）。
    proxy: {
      "/api": {
        target: "http://127.0.0.1:8765",
        changeOrigin: true,
      },
    },
  },
});
